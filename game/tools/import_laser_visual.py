"""Extract LaserBeam's two head pose tables and particle image; never execute it."""
from pathlib import Path
import json
import shutil
from inspect_original import Original
from analyze_reference import REF


def main():
    original = Original()
    lines = ['// Generated by game/tools/import_laser_visual.py from the supplied original.',
             '#pragma once', '#include "engine/core/geometry/vector2.h"',
             '#include <array>', 'namespace game::play {',
             'struct LaserHeadPose {elysia::core::Vector2 position;float rotation;};']
    for name, address in [('Stem', 0x1a0844), ('Head', 0x1a0b20)]:
        lines += [f'// LaserBeam.updateAnimation: ARM table 0x{address:x}, 61 local Y-up poses.',
                  f'inline constexpr std::array<LaserHeadPose,61> kLaser{name}Poses{{{{']
        for frame in range(61):
            x, y, angle = original.unpack('<3f', address + frame * 12)
            def literal(value):
                text = format(value, '.6g')
                return text + ('.0f' if '.' not in text and 'e' not in text else 'f')
            lines.append('    {{' + literal(x) + ',' + literal(y) + '},' + literal(angle) + '},')
        lines.append('}};')
    lines.append('}')
    root = Path(__file__).resolve().parents[2]
    (root/'game/gameplay/laser_visual_poses.h').write_text('\n'.join(lines)+'\n', encoding='utf8')
    source = next((REF/'08_PNG解析/01_独立图片').rglob('stars.png'))
    shutil.copyfile(source, root/'assets/textures/fly/laser_stars.png')
    manifest = root/'assets/configs/manifests/textures_manifest.json'
    data = json.loads(manifest.read_text(encoding='utf8'))
    data['textures']['fly.laser_stars'] = {'path': 'fly/laser_stars.png'}
    manifest.write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', encoding='utf8')


if __name__ == '__main__':
    main()
